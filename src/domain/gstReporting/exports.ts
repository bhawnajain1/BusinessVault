function paiseSum(rows: Row[], key: string): number {
  return rows.reduce((total, row) => {
    const value = row[key];
    if (typeof value !== 'number' || !Number.isSafeInteger(value)) return total;
    const next = total + value;
    if (!Number.isSafeInteger(next)) throw new Error(`GST CA export ${key} exceeds the safe integer range`);
    return next;
  }, 0);
}

const CA_TAX_COLUMNS = ['Taxable Value', 'Integrated Tax Amount', 'Central Tax Amount', 'State/UT Tax Amount', 'Cess Amount'] as const;
const CA_TAX_KEYS: Array<[typeof CA_TAX_COLUMNS[number], keyof GstAmounts]> = [
  ['Taxable Value', 'taxable_paise'], ['Integrated Tax Amount', 'igst_paise'], ['Central Tax Amount', 'cgst_paise'], ['State/UT Tax Amount', 'sgst_paise'], ['Cess Amount', 'cess_paise'],
];

function sumAmounts(rows: Array<Partial<GstAmounts>>): GstAmounts {
  const total: GstAmounts = { taxable_paise: 0, igst_paise: 0, cgst_paise: 0, sgst_paise: 0, cess_paise: 0, pre_round_total_paise: 0, round_off_paise: 0, total_paise: 0 };
  for (const row of rows) for (const key of AMOUNTS) {
    const value = row[key] ?? 0;
    if (!Number.isSafeInteger(value)) throw new Error('GST CA export requires safe integer paise');
    total[key] += value;
    if (!Number.isSafeInteger(total[key])) throw new Error('GST CA export total exceeds the safe integer range');
  }
  return total;
}

function caControl(control: string, expected: GstAmounts, actual: GstAmounts, expectedDocuments: string[], actualDocuments: string[], expectedParties: string[] | null, actualParties: string[] | null, message: string): Row {
  const documentVariance = actualDocuments.length - expectedDocuments.length;
  const partyVariance = expectedParties === null || actualParties === null ? null : actualParties.length - expectedParties.length;
  const status = documentVariance === 0 && (partyVariance === null || partyVariance === 0) && CA_TAX_KEYS.every(([, key]) => expected[key] === actual[key]) ? 'PASS' : 'ERROR';
  return {
    Status: status, Control: control, Message: message,
    'Expected Documents': expectedDocuments.length, 'Export Documents': actualDocuments.length, 'Document Variance': documentVariance,
    'Expected Parties': expectedParties?.length ?? 'N/A', 'Export Parties': actualParties?.length ?? 'N/A', 'Party Variance': partyVariance ?? 'N/A',
    ...Object.fromEntries(CA_TAX_KEYS.flatMap(([label, key]) => [[`Expected ${label}`, expected[key]], [`Export ${label}`, actual[key]], [`Variance ${label}`, actual[key] - expected[key]]])),
  };
}

function documentIds(rows: NormalizedGstDocument[]): string[] { return [...new Set(rows.map(row => `${row.source_entity_type}:${row.source_entity_id}`))]; }
function documentParties(rows: NormalizedGstDocument[]): string[] { return [...new Set(rows.map(row => row.party_gstin || row.party_id).filter(Boolean))]; }
function rowIds(rows: Array<{ source_entity_id: string }>): string[] { return [...new Set(rows.map(row => row.source_entity_id))]; }
function sourceCount(rows: Array<{ source_entity_id?: string; source_entity_ids?: string[] }>): number {
  return new Set(rows.flatMap(row => row.source_entity_ids ?? (row.source_entity_id ? [row.source_entity_id] : []))).size;
}

function caValidationRows(result: MonthlyGstCalculation, kind: 'gstr1' | 'purchase'): Row[] {
  const rows: Row[] = [];
  if (kind === 'gstr1') {
    const documents = result.outwardDocuments.filter(row => row.included);
    const rates = result.outwardRateRows;
    const hsn = result.outwardHsnRows;
    rows.push(caControl('REGISTER_TO_OUTWARD_NET', result.totals.outwardNet, sumAmounts(documents), result.totals.outwardNet.source_entity_ids, documentIds(documents), documentParties(documents), documentParties(documents), 'GSTR-1 register versus normalized outward net.'));
    rows.push(caControl('RATE_ROWS_TO_OUTWARD_NET', result.totals.outwardNet, sumAmounts(rates), result.totals.outwardNet.source_entity_ids, rowIds(rates), documentParties(documents), null, 'All GSTR-1 rate sections versus normalized outward net.'));
    rows.push(caControl('HSN_TO_OUTWARD_NET', result.totals.outwardNet, sumAmounts(hsn), result.totals.outwardNet.source_entity_ids, [...new Set(hsn.flatMap(row => row.source_entity_ids))], null, null, 'Outward HSN/item summary versus normalized outward net.'));
    const seriesCount = result.documentSeries.reduce((total, row) => total + row.net_issued, 0);
    const seriesControl = result.reconciliations.find(row => row.code === 'DOCUMENT_SERIES_NET_ISSUED');
    const expectedSeriesCount = seriesControl?.source_document_count ?? seriesCount;
    rows.push({ Status: seriesCount === expectedSeriesCount ? 'PASS' : 'ERROR', Control: 'DOCUMENT_SERIES_COUNT', Message: 'Document-series net issued count versus engine legal-document reconciliation, including unresolved documents.', 'Expected Documents': expectedSeriesCount, 'Export Documents': seriesCount, 'Document Variance': seriesCount - expectedSeriesCount });
  } else {
    const documents = result.inwardDocuments.filter(row => row.included);
    const notes = result.inwardNotes.filter(row => row.included);
    const purchases = documents.filter(row => !notes.some(note => note.source_entity_type === row.source_entity_type && note.source_entity_id === row.source_entity_id));
    const hsn = result.inwardHsnRows;
    rows.push(caControl('REGISTER_TO_INWARD_NET', result.totals.inwardNet, sumAmounts(documents), result.totals.inwardNet.source_entity_ids, documentIds(documents), documentParties(documents), documentParties(documents), 'Purchase register versus normalized inward net.'));
    rows.push(caControl('PURCHASES_TO_INWARD_GROSS', result.totals.inwardGross, sumAmounts(purchases), result.totals.inwardGross.source_entity_ids, documentIds(purchases), documentParties(purchases), documentParties(purchases), 'Purchase sections versus normalized inward gross.'));
    rows.push(caControl('RETURNS_TO_INWARD_NOTES', result.totals.inwardNotes, sumAmounts(notes), result.totals.inwardNotes.source_entity_ids, documentIds(notes), documentParties(notes), documentParties(notes), 'Purchase credit/debit notes versus normalized inward notes.'));
    rows.push(caControl('HSN_TO_INWARD_NET', result.totals.inwardNet, sumAmounts(hsn), result.totals.inwardNet.source_entity_ids, [...new Set(hsn.flatMap(row => row.source_entity_ids))], null, null, 'Purchase HSN/item summary versus normalized inward net.'));
    for (const head of ['IGST', 'CGST', 'SGST', 'CESS'] as const) {
      const key = `${head.toLowerCase()}_paise` as keyof GstAmounts;
      const approved = result.booksItcRows.filter(row => row.tax_head === head).reduce((total, row) => total + row.approved_paise, 0);
      const expected = result.totals.booksItc.NET_APPROVED[key];
      rows.push({ Status: approved === expected ? 'PASS' : 'ERROR', Control: `ITC_APPROVED_${head}`, Message: `Books ITC approved ${head} versus normalized approved Books ITC.`, 'Expected Approved Books ITC': expected, 'Export Approved Books ITC': approved, 'Variance Approved Books ITC': approved - expected });
    }
  }
  return [
    ...rows,
    ...result.reconciliations.map(row => ({ Status: row.status === 'PASS' ? 'PASS' : row.status === 'WARNING' ? 'WARNING' : 'ERROR', Control: `ENGINE:${row.code}`, Message: row.message })),
    ...result.issues.map(row => ({ Status: row.severity === 'BLOCKING_ERROR' ? 'ERROR' : row.severity === 'WARNING' ? 'WARNING' : 'PASS', Control: `ISSUE:${row.code}`, Message: row.message, 'Document Number': row.document_number ?? '' })),
  ];
}

function caSheet(workbook: ExcelJS.Workbook, name: string, title: string, results: MonthlyGstCalculation[], rows: Row[], documentCount?: number): void {
  const columns = [...new Set(rows.flatMap(row => Object.keys(row)))];
  if (!columns.length) columns.push('No reportable records');
  const sheet = workbook.addWorksheet(name);
  const singleMonth = results.length === 1;
  const totalTaxable = singleMonth ? paiseSum(rows, 'Taxable Value') : null;
  const totalTax = singleMonth ? ['Integrated Tax Amount', 'Central Tax Amount', 'State/UT Tax Amount', 'Cess Amount'].reduce((sum, key) => sum + paiseSum(rows, key), 0) : null;
  sheet.addRow([title]);
  sheet.mergeCells(1, 1, 1, Math.max(columns.length, 1));
  sheet.getRow(1).font = { bold: true, size: 12, color: { argb: 'FFFFFFFF' } };
  sheet.getRow(1).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF1E3A5F' } };
  sheet.addRow(['Period', singleMonth ? results[0].period.periodKey : 'Multiple months - see Tax Period', 'GSTIN', results[0].gstinSnapshot, 'Documents', documentCount ?? rows.length, 'Taxable Value', totalTaxable === null ? 'Month-separated' : excelMoney(totalTaxable), 'Total GST', totalTax === null ? 'Month-separated' : excelMoney(totalTax)]);
  sheet.getRow(2).font = { bold: true };
  sheet.addRow(columns);
  const header = sheet.getRow(3);
  header.font = { bold: true, color: { argb: 'FFFFFFFF' } };
  header.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF365F91' } };
  for (const row of rows) {
    const written = sheet.addRow(columns.map(column => cell(row[column], column === 'Document Date' ? 'document_date' : isCaMoneyColumn(column) ? `${column}_paise` : column, true)));
    for (let index = 1; index <= columns.length; index += 1) {
      const column = columns[index - 1];
      const current = written.getCell(index);
      if (current.value instanceof Date) current.numFmt = 'dd-mmm-yyyy';
      else if (typeof current.value === 'number') current.numFmt = column === 'Rate' || column === 'Total Quantity' ? '0.######' : MONEY_FORMAT;
      else current.numFmt = '@';
    }
  }
  sheet.views = [{ state: 'frozen', ySplit: 3 }];
  sheet.autoFilter = { from: { row: 3, column: 1 }, to: { row: Math.max(3, sheet.rowCount), column: columns.length } };
  for (let index = 1; index <= columns.length; index += 1) sheet.getColumn(index).width = Math.min(36, Math.max(14, columns[index - 1].length + 3));
}

