function money(paise: unknown): string {
  if (typeof paise !== 'number' || !Number.isSafeInteger(paise)) throw new Error('GST export requires safe integer paise');
  // Division near MAX_SAFE_INTEGER can round up before fromMoney floors it.
  if (Math.abs(paise) > EXCEL_MAX_PAISE) {
    const absolute = BigInt(Math.abs(paise));
    return `${paise < 0 ? '-' : ''}${absolute / 100n}.${String(absolute % 100n).padStart(2, '0')}`;
  }
  return fromMoney(paise as Money).replace(/,/g, '');
}

function excelMoney(paise: unknown): number {
  const number = Number(money(paise));
  if (Math.abs(paise as number) > EXCEL_MAX_PAISE || Math.round(number * 100) !== paise) {
    throw new Error('GST XLSX amount cannot preserve paise within Excel 15-digit precision. Download CSV or BusinessVault working JSON for exact values.');
  }
  return number;
}

function selectedResults(results: MonthlyGstCalculation[]): MonthlyGstCalculation[] {
  if (!results.length) throw new Error('Select at least one GST month');
  const first = results[0];
  const periods = new Set<string>();
  for (const result of results) {
    if (result.businessId !== first.businessId || result.gstinSnapshot !== first.gstinSnapshot || result.period.filingFrequency !== first.period.filingFrequency) throw new Error('GST exports require one business registration and filing frequency');
    if (result.period.businessId !== result.businessId || result.period.gstinSnapshot !== result.gstinSnapshot) throw new Error('GST calculation and period registration differ');
    if (result.period.periodType !== 'MONTH' || !/^\d{4}-(0[1-9]|1[0-2])$/.test(result.period.periodKey)) throw new Error('GST exports require monthly calculations');
    if (periods.has(result.period.periodKey)) throw new Error('Duplicate GST period');
    periods.add(result.period.periodKey);
  }
  return [...results].sort((a, b) => a.period.periodKey.localeCompare(b.period.periodKey));
}

function filename(results: MonthlyGstCalculation[], extension: string): string {
  return `BusinessVault-GST-Working-${results[0].period.periodKey}${results.length > 1 ? `-to-${results[results.length - 1].period.periodKey}` : ''}.${extension}`;
}

